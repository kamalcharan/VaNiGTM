// Scopes the VaNi Edge reference stylesheets under `.edge-root`.
//
// The reference (VaNiGTM/docs/EDGE/vani-edge/styles/) styles `body`, `h1`,
// `button` and `:root` directly — fine for a standalone page, a leak inside
// the console. This rewrites every selector so the same rules apply only
// inside the Edge shell, and the output is committed so the CSS the product
// ships is byte-for-byte derived from the reference, not hand-edited.
//
//   node scripts/build-edge-css.mjs [path-to-vani-edge/styles]
//
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const src = resolve(process.argv[2] ?? '../../VaNiGTM/docs/EDGE/vani-edge/styles');
const out = resolve('src/skills/edge/edge.css');
const ROOT = '.edge-root';

function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return s;
  if (s === ':root' || s === 'body' || s === 'html') return ROOT;
  if (s.startsWith('body ')) return ROOT + s.slice(4);
  if (s.startsWith('::')) return `${ROOT} ${s}`;
  return `${ROOT} ${s}`;
}

// Minimal CSS walker: enough for the reference's flat, minified files.
function scope(css) {
  let out = '', i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) { out += css.slice(i); break; }
    const head = css.slice(i, open).trim();
    if (head.startsWith('@')) {
      // at-rule with a block: @media / @keyframes / @supports
      let depth = 1, j = open + 1;
      while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
      const body = css.slice(open + 1, j - 1);
      out += `${head}{${head.startsWith('@keyframes') || head.startsWith('@font-face') ? body : scope(body)}}`;
      i = j;
      continue;
    }
    const close = css.indexOf('}', open);
    const body = css.slice(open + 1, close);
    out += `${head.split(',').map(scopeSelector).join(',')}{${body}}`;
    i = close + 1;
  }
  return out;
}

// The console's globals.css sets body{font-size:14px;font-weight:300;
// line-height:1.65}, h1-h3{font-family:var(--display);font-weight:700;
// letter-spacing:-.5px} and *{margin:0;padding:0}. The reference assumes the
// browser's defaults for all of these — its <strong> is "bolder" than a 400
// body, its paragraphs keep their 1em bottom margin, its lists their indent.
// Restore those defaults under .edge-root BEFORE the reference rules, so
// the reference still wins wherever it sets its own value.
const HOST_RESET = `/* ── host reset: console globals → browser defaults ── */
${ROOT}{font-size:16px;font-weight:400;line-height:normal;-webkit-font-smoothing:auto}
${ROOT} h1,${ROOT} h2,${ROOT} h3,${ROOT} h4{font-family:inherit;font-weight:bold;letter-spacing:normal}
${ROOT} h1{font-size:2em;margin:.67em 0}${ROOT} h2{font-size:1.5em;margin:.83em 0}${ROOT} h3{font-size:1.17em;margin:1em 0}${ROOT} h4{margin:1.33em 0}
${ROOT} p,${ROOT} dl,${ROOT} ul,${ROOT} ol,${ROOT} blockquote,${ROOT} figure,${ROOT} pre{margin:1em 0}
${ROOT} ul,${ROOT} ol{padding-left:40px}${ROOT} dd{margin-left:40px}
${ROOT} fieldset{margin:0 2px;padding:.35em .75em .625em;border:2px groove ThreeDFace}${ROOT} legend{padding:0 2px}
${ROOT} input,${ROOT} textarea,${ROOT} select{padding:1px 2px}${ROOT} textarea{padding:2px}${ROOT} button{padding:1px 6px}
${ROOT} table{border-spacing:2px}${ROOT} td,${ROOT} th{padding:1px}${ROOT} th{font-weight:bold}
${ROOT} strong,${ROOT} b{font-weight:bold}${ROOT} small{font-size:smaller}${ROOT} code,${ROOT} pre{font-family:monospace}
`;

const files = ['tokens.css', 'app.css', 'mission.css'];
const scoped = files.map((f) => `/* ── ${f} ── */\n${scope(readFileSync(resolve(src, f), 'utf8'))}`).join('\n');
writeFileSync(out, `/* GENERATED by scripts/build-edge-css.mjs from ${files.join(', ')} — do not edit by hand. */\n${HOST_RESET}${scoped}\n`);
console.log('wrote', out, scoped.length, 'bytes');
